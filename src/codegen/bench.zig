/// Writes `v` as a Zig literal of its type, every field by name: a string
/// as a string, a slice as `&.{ ... }`, a float exactly (`fmtF64`).
fn literal(w: *std.Io.Writer, v: anytype) std.Io.Writer.Error!void {
    const T = @TypeOf(v);
    switch (@typeInfo(T)) {
        .float => try w.print("{f}", .{fmtF64(v)}),
        .int, .comptime_int => try w.print("{d}", .{v}),
        .bool => try w.print("{}", .{v}),
        .@"enum" => try w.print(".{f}", .{std.zig.fmtId(@tagName(v))}),
        .optional => if (v) |x| try literal(w, x) else try w.writeAll("null"),
        .array => {
            try w.writeAll(".{");
            for (v, 0..) |x, i| {
                try w.writeAll(if (i == 0) " " else ", ");
                try literal(w, x);
            }
            try w.writeAll(" }");
        },
        .pointer => |p| {
            comptime assert(p.size == .slice);
            if (p.child == u8) return w.print("\"{f}\"", .{std.zig.fmtString(v)});
            try w.writeAll("&.{");
            for (v, 0..) |x, i| {
                try w.writeAll(if (i == 0) " " else ", ");
                try literal(w, x);
            }
            try w.writeAll(if (v.len == 0) "}" else " }");
        },
        .@"struct" => |s| {
            try w.writeAll(".{");
            inline for (s.field_names, 0..) |name, i| {
                try w.print("{s}.{f} = ", .{ if (i == 0) " " else ", ", std.zig.fmtId(name) });
                try literal(w, @field(v, name));
            }
            try w.writeAll(" }");
        },
        else => @compileError("bench: no literal for " ++ @typeName(T)),
    }
}

/// Asserts that `fmtF64(x)` is a literal Zig reads back as `x`, bit for bit.
fn expectExactLiteral(x: f64) !void {
    var buf: [512]u8 = undefined;
    const lit = try std.mem.print(&buf, "{f}", .{fmtF64(x)});
    errdefer std.debug.print("fmtF64({e}) = {s}\n", .{ x, lit });
    const unsigned = if (lit[0] == '-') lit[1..] else lit;
    switch (std.zig.parseNumberLiteral(unsigned)) {
        .float => {},
        .int => |v| {
            try std.testing.expect(!(x == 0 and std.math.signbit(x)));
            const nearest: f64 = @floatFromInt(v);
            try std.testing.expect(nearest < 0x1p64 and @as(u64, @intFromFloat(nearest)) == v);
        },
        .big_int, .failure => return error.TestUnexpectedResult,
    }
    const back = try std.fmt.parseFloat(f64, lit);
    try std.testing.expectEqual(@as(u64, @bitCast(x)), @as(u64, @bitCast(back)));
}

test fmtF64 {
    // Oracle: Zig's own reading of the text. `parseNumberLiteral` classifies
    // it as the tokenizer does: a float literal is rounded correctly, but an
    // integer literal is a comptime_int, which an f64 holds exactly only when
    // the double is that integer, and which has no negative zero.
    const edge = [_]f64{ 0.0, -0.0, 1.0, -1.0, 0.5, 2.5e-3, 300.15, 1e20, 0x1p53, 0x1p53 + 2.0, 1e23, -1e23, std.math.floatMax(f64), std.math.floatMin(f64), std.math.floatTrueMin(f64), -std.math.floatTrueMin(f64) };
    for (edge) |x| try expectExactLiteral(x);
    var prng = std.Random.DefaultPrng.init(0x5eed_f64);
    const r = prng.random();
    for (0..4096) |_| {
        const x: f64 = @bitCast(r.int(u64));
        if (!std.math.isFinite(x)) continue;
        try expectExactLiteral(x);
    }
    var buf: [32]u8 = undefined;
    try std.testing.expectEqualStrings("std.math.nan(f64)", try std.mem.print(&buf, "{f}", .{fmtF64(std.math.nan(f64))}));
    try std.testing.expectEqualStrings("-std.math.inf(f64)", try std.mem.print(&buf, "{f}", .{fmtF64(-std.math.inf(f64))}));
}

