#!/usr/bin/env python3
"""Writes one `.v` fixture for diff-native's generator (the oracle-set hole
the corpus rarely hits: an operator inlined at a width/sign edge).

    tools/gen_native_v.py SEED > tests/differential/native/gen_SEED.v

Oracle: the interpreter, diff-native (`zig build diff-native` runs the
built `--emit-exe` binary twice, as built and with `VERA_INTERPRET=1`, and
the two must agree byte for byte).

Deterministic in `SEED` alone (`random.seed(SEED)`): regs of widths
{1, 7, 8, 31, 32, 33, 63, 64, 65}, signed and unsigned, each initialised
from a sized constant with an x or z bit one time in four; 256 `initial`
assignments of random expression trees (depth <= 4) over
`src/codegen/digital_next/native.zig`'s inlined operators (the four
arithmetic and bitwise binary ops, the six reductions, the shifts, the
relational and logical ops, `?:`, a constant part-select) and, for a
quarter of them, a `case`/`casez`/`casex` of 4 arms in place of a plain
assignment; the 65-bit regs feed some trees so some land on `native.zig`'s
`leaf` fallback (over 64 bits, `small.fits` is false). One
`$display("%b", r)` per target, so a byte difference has a line to name.
"""
import random
import sys

WIDTHS = [1, 7, 8, 31, 32, 33, 63, 64, 65]
BINARY = ["+", "-", "*", "&", "|", "^", "~^", "<<", ">>", "<<<", ">>>", "==", "!=", "===", "!==", "<", "<=", ">", ">=", "&&", "||"]
UNARY = ["~", "-", "!", "&", "~&", "|", "~|", "^", "~^"]
TREES = 256
DEPTH_MAX = 4


def sized_const(rng, width, x_or_z):
    """A `width`-bit sized literal; one digit is `x`/`z` when `x_or_z`."""
    digits = [rng.choice("01") for _ in range(width)]
    if x_or_z:
        digits[rng.randrange(width)] = rng.choice("xz")
    return f"{width}'b{''.join(digits)}"


def leaf(rng, regs):
    """A register reference, a constant part-select, or a sized literal."""
    pick = rng.randrange(3)
    if pick == 0:
        return rng.choice(regs)[0]
    if pick == 1:
        name, width, _ = rng.choice(regs)
        if width <= 1:
            return name
        hi = rng.randrange(width)
        lo = rng.randrange(hi + 1)
        return f"{name}[{hi}:{lo}]" if hi != lo else f"{name}[{hi}]"
    width = rng.choice(WIDTHS)
    return sized_const(rng, width, rng.randrange(4) == 0)


def expr(rng, regs, depth):
    """A random expression tree, `UNARY`/`BINARY`/`?:` over `leaf`s, depth
    bounded by `DEPTH_MAX` (asserted: every recursive call passes depth - 1,
    so the tree cannot exceed the cap)."""
    assert depth <= DEPTH_MAX
    if depth == 0 or rng.randrange(3) == 0:
        return leaf(rng, regs)
    kind = rng.randrange(3)
    if kind == 0:
        op = rng.choice(UNARY)
        return f"({op}({expr(rng, regs, depth - 1)}))"
    if kind == 1:
        op = rng.choice(BINARY)
        return f"({expr(rng, regs, depth - 1)} {op} {expr(rng, regs, depth - 1)})"
    c = expr(rng, regs, depth - 1)
    a = expr(rng, regs, depth - 1)
    b = expr(rng, regs, depth - 1)
    return f"({c} ? {a} : {b})"


def case_stmt(rng, regs, target, result_width):
    """A `case`/`casez`/`casex` of 4 arms over a scrutinee, assigning
    `target` differently per arm; a `default` arm so the reg is defined on
    every path (Verilog, not `Program.Case.fallback`'s own semantics)."""
    scrut_width = rng.choice(WIDTHS)
    kw = rng.choice(["case", "casez", "casex"])
    scrutinee = leaf(rng, regs) if rng.randrange(2) else expr(rng, regs, 2)
    lines = [f"    {kw} ({scrutinee})"]
    _ = result_width  # The target's own declared width sizes the assignment.
    for _ in range(4):
        label = sized_const(rng, scrut_width, kw != "case" and rng.randrange(2) == 0)
        lines.append(f"      {label}: {target} = {expr(rng, regs, DEPTH_MAX - 1)};")
    lines.append(f"      default: {target} = {expr(rng, regs, 1)};")
    lines.append("    endcase")
    return "\n".join(lines)


def main(seed):
    rng = random.Random(seed)
    regs = []  # (name, width, signed)
    decls = []
    for width in WIDTHS:
        for signed in (False, True):
            name = f"r_w{width}_{'s' if signed else 'u'}"
            value = sized_const(rng, width, rng.randrange(4) == 0)
            kw = "reg signed" if signed else "reg"
            rng_decl = f"[{width - 1}:0] " if width > 1 else ""
            decls.append(f"  {kw} {rng_decl}{name} = {value};")
            regs.append((name, width, signed))

    targets = []
    stmts = []
    for i in range(TREES):
        width = rng.choice(WIDTHS)
        name = f"t{i}"
        targets.append(f"  reg [{width - 1}:0] {name};")
        if rng.randrange(4) == 0:
            stmts.append(case_stmt(rng, regs, name, width))
        else:
            stmts.append(f"    {name} = {expr(rng, regs, DEPTH_MAX)};")
        stmts.append(f'    $display("%b", {name});')

    print(f"// Generated by tools/gen_native_v.py {seed} (diff-native's generator).")
    print("// Oracle: the interpreter, diff-native.")
    print("`timescale 1ns/1ps")
    print(f"module gen_{seed};")
    for d in decls:
        print(d)
    for t in targets:
        print(t)
    print("  initial begin")
    for s in stmts:
        print(s)
    print("    $finish(0);")
    print("  end")
    print("endmodule")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: tools/gen_native_v.py SEED")
    main(int(sys.argv[1]))
