//! The analog testbench backend behind `--run` and `--emit-exe`
//! (docs/rewrite/exe.md): a fixture's `//!` directives (`Spec`) and the
//! analysed device (`Air.Device`) in, a runner's root out. The runner is
//! data: the bench as one `std_sim.bench.Config` literal beside the device;
//! the host that runs it (the solve, the gates, the checks, the §8 mixed
//! kernel) is `std_sim.bench`, shipped once and never spliced. `link`
//! builds it beside the device; it prints the transcript the fixture's
//! harness compares. Named for what it writes; renamed `exe` at the
//! switch-over, when the old `codegen/exe` goes.
//!
//! ```zig
//! const s = try bench.Spec.parse(arena, source, null);
//! var facts = try bench.facts(arena, &analysis.device);
//! var aw: std.Io.Writer.Allocating = .init(gpa);
//! try bench.writeRunner(&aw.writer, stem, &s.bench, facts);
//! // then `link.buildExe(file, ..., device_text, aw.written())`
//! ```
//!
//! Cites: §2.4, §4.5.2; each `std_sim.bench` file cites its own clauses.
//!
//! Contents:
//! - from `bench/spec.zig`: `Spec`, `Bench`, `Harness`, `Facts` (= `std_sim.bench.Config`), `Digital`, `Binding`, `ParseError`, `RenderError`, `points_max`
//! - `pub fn writeRunner(w: *std.Io.Writer, title: []const u8, bench: *const Bench, facts: Facts) RenderError!void`
//! - `pub fn facts(arena: Allocator, device: *const Air.Device) Allocator.Error!Facts`
//! - `pub fn digital(arena: Allocator, program: *const std_sim.Program, names: []const Digital.Name) Allocator.Error!Digital`
//! - `pub fn gridEvent(air: *const Air) ?Air.Inst.Index`
//! - `pub fn fmtF64(x: f64) std.fmt.Alt(f64, formatF64)`, `pub fn formatF64(x: f64, w: *std.Io.Writer) std.Io.Writer.Error!void`

const std = @import("std");
const assert = std.debug.assert;
const Allocator = std.mem.Allocator;
const Air = @import("air");
const SysFn = @import("vams").SysFn;
const std_sim = @import("std_sim");
const spec = @import("bench/spec.zig");

pub const Spec = spec.Spec;
pub const Bench = spec.Bench;
pub const Harness = spec.Harness;
pub const Facts = spec.Config;
pub const Digital = spec.Digital;
pub const Binding = spec.Binding;
pub const ParseError = spec.ParseError;
pub const RenderError = spec.RenderError;
pub const points_max = spec.points_max;

/// Writes the runner's root for `bench` to `w`: the device, the bench and
/// `facts` as one `vera_bench` literal (`title` keys the transcript: the
/// fixture's file stem), and `std_sim.bench`'s `main`. The runner prints to
/// stderr through `std.debug.print`, the stream generated `$strobe` uses, so
/// the interleaving is deterministic. Fails with `error.TooManyPoints`,
/// writing nothing, past `points_max`.
pub fn writeRunner(w: *std.Io.Writer, title: []const u8, bench: *const Bench, facts_: Facts) RenderError!void {
    _ = try std_sim.bench_data.pointCount(bench);
    assert(bench.times_s.len != 0);
    var cfg = facts_;
    cfg.title = title;
    cfg.bench = bench.*;
    try w.print(
        \\// GENERATED BY VerA — DO NOT EDIT.
        \\// A runnable Verilog-A testbench: the device's own `$strobe` output plus
        \\// the residual and Jacobian at each `//!`-declared operating point
        \\// (`std_sim.bench` runs it).
        \\
        \\const std = @import("std");
        \\const bench = @import("std_sim").bench;
        \\pub const D = @import("device");
        \\/// Read by `contract.validating`: run the contract's conformance checks.
        \\pub const vera_validate_contract = {};
        \\/// Set while a gate evaluates the device around a point: the printing
        \\/// kernels' §4.3.2 report stays quiet (`zDomain`).
        \\pub var vera_domain_muted: bool = false;
        \\pub const veraDiag = bench.veraDiag;
        \\pub const main = bench.main;
        \\pub const vera_bench: bench.Config =
    , .{facts_.validate_contract});
    try literal(w, cfg);
    try w.writeAll(";\n");
}

/// What the runner needs from the device besides its text: the §4.5.2
/// operator unknowns' `U` indices, ascending (never forced). The caller
/// sets the switches. `op_states` is allocated in `arena`.
pub fn facts(arena: Allocator, device: *const Air.Device) Allocator.Error!Facts {
    const kinds = device.nodes.items(.kind);
    var ops: std.ArrayList(u32) = .empty;
    for (kinds, 0..) |k, i| if (k == .op_state) try ops.append(arena, @intCast(i));
    assert(ops.items.len <= kinds.len);
    // ponytail: `mem_bytes` 0 sizes `bigStack` by unknowns alone; count the
    // §3.2.2 arrays when a large array overflows the 8 MiB main stack.
    return .{ .title = "", .op_states = ops.items };
}

/// A mixed design's digital half as the runner embeds it (`Facts.mixed`):
/// `program` saved by `std_sim.serial`, beside its `names`; in `arena`.
pub fn digital(arena: Allocator, program: *const std_sim.Program, names: []const Digital.Name) Allocator.Error!Digital {
    var aw: std.Io.Writer.Allocating = .init(arena);
    std_sim.serial.save(program, &aw.writer) catch return error.OutOfMemory;
    assert(aw.written().len != 0);
    return .{ .program = aw.written(), .names = names };
}

/// The first §5.10.3 `cross`, `above` or `timer` call in `air`, or null:
/// the fixed-grid runner inserts no timepoint at it, so it fires at the
/// first `//! time` past its own (W0750 points at it).
pub fn gridEvent(air: *const Air) ?Air.Inst.Index {
    const tags = air.instructions.items(.tag);
    const data = air.instructions.items(.data);
    for (tags, data, 0..) |t, d, i| {
        if (t != .call) continue;
        const callee = air.extraData(Air.Call, d.ty_pl.payload).data.callee;
        const ev = for ([_]SysFn.Tag{ .cross, .above, .timer }) |e| {
            if (callee == @backingInt(e)) break true;
        } else false;
        if (ev) return @fromBackingInt(@intCast(i));
    }
    return null;
}

/// Formats `x` as a Zig expression that evaluates to the same f64, bit for
/// bit, wherever an f64 is expected: a shortest round-trip literal, or a
/// `std.math` call for inf and nan, which have no literal.
pub fn fmtF64(x: f64) std.fmt.Alt(f64, formatF64) {
    return .{ .data = x };
}

/// The `fmtF64` formatter.
pub fn formatF64(x: f64, w: *std.Io.Writer) std.Io.Writer.Error!void {
    if (std.math.isNan(x)) return w.writeAll("std.math.nan(f64)");
    if (std.math.isInf(x)) return w.writeAll(if (x > 0) "std.math.inf(f64)" else "-std.math.inf(f64)");
    // `{d}` writes these as integer literals, which Zig reads as a
    // comptime_int: `-0` loses its sign, and past 2^53 the shortest digits
    // are not the double's own integer. `{e}` is a float literal.
    if (x == 0 and std.math.signbit(x)) return w.writeAll("-0.0");
    if (@abs(x) >= 0x1p53) return w.print("{e}", .{x});
    assert(std.math.isFinite(x));
    try w.print("{d}", .{x});
}

